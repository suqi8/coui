    /** The lazy list items of the body. */
    private fun body() {
        val keys = HashSet<String>()
        s.body.forEachIndexed { i, b ->
            val base = when (b) {
                is Block.CardRun -> b.category?.item?.label?.let { Names.slug(it, 3) }?.takeIf { it.isNotEmpty() } ?: "card${i + 1}"
                else -> Names.snake(b.parts.first().kind.key.replaceFirstChar { it.uppercaseChar() }) + "${i + 1}"
            }
            var key = base
            var n = 2
            while (!keys.add(key)) key = "${base}_${n++}"
            w.block("item(key = \"$key\") {") { writeBlock(b, inset = true) }
        }
    }

    /** One block in a column; [inset] adds the 16dp page margins (pages), sheets and dialogs have their own. */
    private fun writeBlock(b: Block, inset: Boolean) {
        when (b) {
            is Block.CardRun -> {
                b.category?.let { c ->
                    notes(c.item)
                    f.import("io.github.suqi8.coui.kmp.preference.PreferenceCategory")
                    w.line("PreferenceCategory(title = ${str(c.item.label, "category")})")
                }
                cardRun(b.run, mod(if (inset) padding() else bottomPadding()))
            }

            is Block.Single -> part(b.part, columnModifier(b.part, inset), inRow = false)

            is Block.Line -> partsLine(b.parts, inset)

            is Block.Grid -> {
                f.import("androidx.compose.foundation.layout.Arrangement", "androidx.compose.foundation.layout.Column")
                w.call("Column", listOf(Arg.V("modifier", mod((if (inset) padding() else bottomPadding()))), Arg.V("verticalArrangement", "Arrangement.spacedBy(${dp(12f)})"))) {
                    b.lines.forEach { l -> partsLine(l, inset = false, bottom = false) }
                }
            }
        }
    }

    private fun bottomPadding(): String {
        f.import("androidx.compose.foundation.layout.padding")
        return ".padding(bottom = ${dp(16f)})"
    }

    private fun partsLine(parts: List<Part>, inset: Boolean, bottom: Boolean = true) {
        f.import(
            "androidx.compose.foundation.layout.Arrangement",
            "androidx.compose.foundation.layout.Row",
            "androidx.compose.foundation.layout.fillMaxWidth",
            "androidx.compose.ui.Alignment",
        )
        val m = ".fillMaxWidth()" + when {
            inset && bottom -> padding()
            bottom -> bottomPadding()
            else -> ""
        }
        w.call(
            "Row",
            listOf(
                Arg.V("modifier", mod(m)),
                Arg.V("horizontalArrangement", "Arrangement.spacedBy(${dp(12f)})"),
                Arg.V("verticalAlignment", "Alignment.CenterVertically"),
            ),
        ) {
            parts.forEach { p -> part(p, rowModifier(p), inRow = true) }
        }
    }

    /** Whether a part stretches to share a line with others. */
    private fun stretches(p: Part): Boolean = when (p.kind) {
        Kind.IconButton, Kind.Chip, Kind.Fab -> false
        Kind.Button -> p.items.size > 1 || p.item.size == null
        Kind.Progress -> p.item.variant == null || p.item.variant == "linear"
        else -> true
    }

    private fun rowModifier(p: Part): String? = if (stretches(p)) {
        val width = p.item.size
        if (p.kind == Kind.Button && p.items.size == 1 && width != null) {
            f.import("androidx.compose.foundation.layout.width")
            mod(".width(${dp(width)})")
        } else {
            mod(".weight(1f)")
        }
    } else {
        null
    }

    private fun columnModifier(p: Part, inset: Boolean): String? {
        val page = if (inset) padding() else bottomPadding()
        fun fill(): String {
            f.import("androidx.compose.foundation.layout.fillMaxWidth")
            return ".fillMaxWidth()"
        }
        return when (p.kind) {
            Kind.Category -> null

            Kind.Text -> mod(if (inset) ".padding(horizontal = ${dp(16f)}).padding(bottom = ${dp(8f)})".also { f.import("androidx.compose.foundation.layout.padding") } else bottomPadding())

            Kind.Divider -> mod(".padding(${if (inset) "horizontal = ${dp(16f)}, " else ""}vertical = ${dp(8f)})".also { f.import("androidx.compose.foundation.layout.padding") })

            Kind.SearchBar, Kind.Tabs -> mod(bottomPadding())

            Kind.EmptyState -> mod(fill() + bottomPadding())

            Kind.TextField, Kind.Slider, Kind.Image -> mod(page + fill())

            Kind.Progress -> mod(page + if (p.item.variant == null || p.item.variant == "linear") fill() else "")

            Kind.Button -> mod(page + if (p.box.w >= contentWidth - 8f && (p.items.size > 1 || p.item.size == null)) fill() else "")

            Kind.Card -> mod(
                page + (
                    p.item.size?.takeIf { it < contentWidth - 8f }?.let {
                        f.import("androidx.compose.foundation.layout.width")
                        ".width(${dp(it)})"
                    } ?: ""
                    ),
            )

            else -> mod(page)
        }
    }

    /** Writes a part; [modifier] is a full `Modifier…` expression or null. */
    private fun part(p: Part, modifier: String?, inRow: Boolean) {
        when {
            p.isRowRun -> cardRun(p, modifier ?: mod(""))

            p.items.size > 1 -> {
                f.import("androidx.compose.foundation.layout.Arrangement", "androidx.compose.foundation.layout.Row")
                val fillRun = p.box.w >= contentWidth - 8f
                w.call("Row", listOfNotNull(modifier?.let { Arg.V("modifier", it) }, Arg.V("horizontalArrangement", "Arrangement.spacedBy(${dp(12f)})"))) {
                    p.items.forEach { item ->
                        val width = item.size
                        val m = when {
                            width != null -> {
                                f.import("androidx.compose.foundation.layout.width")
                                mod(".width(${dp(width)})")
                            }

                            fillRun && p.kind == Kind.Button -> mod(".weight(1f)")

                            else -> null
                        }
                        item(p, item, m)
                    }
                }
            }

            else -> item(p, p.item, modifier)
        }
    }

    private fun cardRun(p: Part, modifier: String) {
        f.import("io.github.suqi8.coui.kmp.basic.Card", "io.github.suqi8.coui.kmp.basic.CardListGroup")
        w.block("Card(modifier = $modifier) {") {
            block("CardListGroup {") {
                p.items.forEach { item ->
                    block("item {") { row(p, item) }
                }
            }
        }
    }

