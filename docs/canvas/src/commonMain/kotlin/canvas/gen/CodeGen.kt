/** One generated source or resource file; [path] is relative to the project root. */
data class GeneratedFile(val path: String, val content: String)

/**
 * Turns a design into Kotlin that follows the `coui-app` skill: one page per screen, the coui-nav
 * navigation, the themed app root and the string resources.
 */
object CodeGenerator {
    /** The name of the generated string resource file. */
    const val STRINGS_FILE = "strings_canvas.xml"

    fun generate(doc: CanvasDoc, packageName: String = "com.example.app", boxOf: (Group) -> Box = { doc.estimatedBox(it) }): List<GeneratedFile> {
        val plan = Structure.analyze(doc, boxOf)
        if (plan.screens.isEmpty()) return emptyList()
        val pkg = packageName.trim().ifEmpty { "com.example.app" }
        val layout = ProjectLayout(doc.theme.platform, pkg)
        val strings = StringTable()
        val files = mutableListOf<GeneratedFile>()
        plan.screens.forEach { s ->
            files += GeneratedFile(layout.kotlin("${s.ident}Page.kt"), PageWriter(doc, plan, s, pkg, strings).write())
        }
        files += GeneratedFile(layout.kotlin("Navigation.kt"), navigationFile(doc, plan, pkg))
        files += GeneratedFile(layout.kotlin("App.kt"), appFile(doc, pkg))
        val chinese = strings.entries.values.any { Names.hasCjk(it) }
        files += GeneratedFile(layout.resource("values"), strings.xml(if (chinese) TODO_EN else null))
        files += GeneratedFile(layout.resource("values-zh"), strings.xml(if (chinese) null else TODO_ZH))
        return files
    }

    private const val TODO_EN = "TODO: translate these strings into English; the design's labels are Chinese and are copied here as they are."
    private const val TODO_ZH = "TODO: translate these strings into Simplified Chinese; they are copied from the design's English labels."

    private fun header(doc: CanvasDoc): String = "// Generated by COUI Canvas" + (doc.title.takeIf { it.isNotBlank() }?.let { " from \"${oneLine(it)}\"" } ?: "") + ".\n"

    private fun appFile(doc: CanvasDoc, pkg: String): String {
        val f = KtFile(pkg)
        val theme = doc.theme
        val key = parseColor(theme.keyColor)
        val mode = when {
            theme.bothModes -> if (key != null) "MonetSystem" else "System"
            theme.dark -> if (key != null) "MonetDark" else "Dark"
            else -> if (key != null) "MonetLight" else "Light"
        }
        f.import("androidx.compose.runtime.Composable", "androidx.compose.runtime.remember", "androidx.compose.ui.Modifier")
        f.import("io.github.suqi8.coui.kmp.theme.COUITheme", "io.github.suqi8.coui.kmp.theme.ColorSchemeMode", "io.github.suqi8.coui.kmp.theme.ThemeController")
        val w = f.w
        w.line("/** The app root: the COUI theme around the navigation. */")
        w.line("@Composable")
        w.block("fun App(modifier: Modifier = Modifier) {") {
            if (key != null) {
                f.import("androidx.compose.ui.graphics.Color")
                w.line("// The design's key colour: the Monet modes generate the colour scheme from it.")
                w.block("val controller = remember {") {
                    w.line("ThemeController(ColorSchemeMode.$mode, keyColor = Color($key))")
                }
            } else {
                w.line("val controller = remember { ThemeController(ColorSchemeMode.$mode) }")
            }
            w.block("COUITheme(controller = controller) {") {
                w.line("AppNavigation(modifier = modifier)")
            }
        }
        val res = "$pkg.generated.resources"
        val note = header(doc) +
            "//\n" +
            "// CouiPage, CouiPageScaffold, CouiTopBarStyle, isWideWindow, couiPageScroll and panelBlur come from\n" +
            "// CouiPage.kt and CouiBlur.kt of the coui-app skill's scaffold (references/scaffold.md): copy both\n" +
            "// files into this package. Strings are Compose resources: set\n" +
            "// compose.resources { packageOfResClass = \"$res\" } in the module's build file.\n"
        return f.render(note)
    }

    private fun navigationFile(doc: CanvasDoc, plan: AppPlan, pkg: String): String {
        val f = KtFile(pkg)
        val w = f.w
        f.import("androidx.compose.runtime.Composable", "androidx.compose.ui.Modifier", "kotlinx.serialization.Serializable")
        f.import("io.github.suqi8.coui.kmp.nav.core.NavBackStack", "io.github.suqi8.coui.kmp.nav.core.NavDisplay", "io.github.suqi8.coui.kmp.nav.core.NavKey")
        f.import("io.github.suqi8.coui.kmp.nav.core.rememberNavBackStack")
        val start = plan.start ?: plan.screens.first()
        w.line("/** The screens of the app. */")
        w.line("@Serializable")
        w.block("sealed interface Route : NavKey {") {
            plan.screens.forEachIndexed { i, s ->
                if (i > 0) w.line()
                w.line("@Serializable")
                w.line("data object ${s.ident} : Route")
            }
        }
        w.line()
        var fade = false
        w.line("/** The app's navigation; system back and swipe back pop the back stack. */")
        w.line("@Composable")
        w.block("fun AppNavigation(modifier: Modifier = Modifier) {") {
            w.line("val backStack = rememberNavBackStack<Route>(Route.${start.ident})")
            w.call(
                "NavDisplay",
                listOf(Arg.V("backStack", "backStack"), Arg.V("modifier", "modifier"), Arg.V("onBack", "{ backStack.removeLastOrNull() }")),
            ) {
                plan.screens.forEach { s ->
                    val transition = when (plan.transitionInto(s.frame.id)) {
                        Action.TRANSITION_UP -> "NavTransitions.Modal"
                        Action.TRANSITION_NONE -> "NavTransitions.None"
                        Action.TRANSITION_FADE -> "FadeTransition".also { fade = true }
                        else -> null
                    }
                    if (transition?.startsWith("NavTransitions") == true) f.import("io.github.suqi8.coui.kmp.nav.transition.NavTransitions")
                    val open = if (transition != null) "entry<Route.${s.ident}>(transition = $transition) {" else "entry<Route.${s.ident}> {"
                    w.block(open) {
                        val args = pageCallbacks(plan, s).map { cb ->
                            val body = if (cb.target == null) "{ backStack.removeLastOrNull() }" else "{ backStack.open(Route.${cb.target.ident}) }"
                            Arg.V(cb.name, body)
                        }
                        w.call("${s.ident}Page", args)
                    }
                }
            }
        }
        w.line()
        w.line("/** Opens [route], or returns to it when it is already on the back stack (a route may be on it once). */")
        w.block("private fun NavBackStack.open(route: Route) {") {
            w.line("val index = indexOf(route)")
            w.line("if (index < 0) {")
            w.indented { w.line("add(route)") }
            w.line("} else {")
            w.indented { w.line("while (size > index + 1) removeAt(lastIndex)") }
            w.line("}")
        }
        if (fade) {
            f.import("io.github.suqi8.coui.kmp.nav.transition.NavTransition", "io.github.suqi8.coui.kmp.nav.transition.navGraphicsTransition")
            w.line()
            w.line("/** Fades the entering page in; the page below stays as it is. */")
            w.block("private val FadeTransition: NavTransition = navGraphicsTransition { scope ->") {
                w.line("if (scope.relativeDepth <= 0f) alpha = 1f + scope.relativeDepth.coerceIn(-1f, 0f)")
            }
        }
        return f.render(header(doc))
    }

    /** `0xAARRGGBB` from `#RRGGBB` / `#AARRGGBB`, or null. */
    internal fun parseColor(hex: String?): String? {
        val h = hex?.trim()?.removePrefix("#") ?: return null
        if (!h.all { it.isDigit() || it.lowercaseChar() in 'a'..'f' }) return null
        return when (h.length) {
            6 -> "0xFF${h.uppercase()}"
            8 -> "0x${h.uppercase()}"
            else -> null
        }
    }
}

/** A navigation callback of a page: `onBack` ([target] null) or `onOpen<Ident>`. */
internal data class Callback(val name: String, val target: ScreenPlan?)

/** The callbacks a page takes, in a stable order: the screens it opens, then back. */
internal fun pageCallbacks(plan: AppPlan, s: ScreenPlan): List<Callback> {
    val opens = plan.tapTargets(s.frame.id).map { Callback("onOpen${it.ident}", it) }
    val back = if (plan.goesBack(s.frame.id)) listOf(Callback("onBack", null)) else emptyList()
    return opens + back
}

private fun oneLine(s: String): String = s.replace('\n', ' ').replace('\r', ' ').trim()

/** Where files go for the chosen platform. */
private class ProjectLayout(platform: String, pkg: String) {
    private val multiplatform = platform == DocTheme.PLATFORM_MULTIPLATFORM
    private val pkgPath = pkg.replace('.', '/')

    fun kotlin(file: String): String = if (multiplatform) "composeApp/src/commonMain/kotlin/$pkgPath/$file" else "app/src/main/java/$pkgPath/$file"

    fun resource(dir: String): String = (if (multiplatform) "composeApp/src/commonMain/composeResources" else "app/src/main/composeResources") + "/$dir/${CodeGenerator.STRINGS_FILE}"
}

/** Every user-visible text as a string resource. */
internal class StringTable {
    /** Key -> text, in the order they were used. */
    val entries = LinkedHashMap<String, String>()
    private val byText = HashMap<Pair<String, String>, String>()

    /**
     * The key of [text] on the screen with resource prefix [prefix]; the same text on one screen
     * shares a key. [hint] names the key when the text has no ASCII words (e.g. Chinese labels).
     */
    fun key(prefix: String, text: String, hint: String): String {
        byText[prefix to text]?.let { return it }
        val base = "${prefix}_" + Names.slug(text).ifEmpty { hint }
        var key = base
        var n = 2
        while (key in entries) key = "${base}_${n++}"
        entries[key] = text
        byText[prefix to text] = key
        return key
    }

    fun xml(comment: String?): String = buildString {
        append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        append("<!-- Generated by COUI Canvas. -->\n")
        comment?.let { append("<!-- ").append(xmlComment(it)).append(" -->\n") }
        append("<resources>\n")
        entries.forEach { (k, v) -> append("    <string name=\"").append(k).append("\">").append(escapeXml(v)).append("</string>\n") }
        append("</resources>\n")
    }
}

/** Escapes a string resource value: XML entities, Android quote escapes, `%`, new lines and tabs. */
internal fun escapeXml(text: String): String = buildString {
    text.forEach { c ->
        when (c) {
            '&' -> append("&amp;")
            '<' -> append("&lt;")
            '>' -> append("&gt;")
            '\'' -> append("\\'")
            '"' -> append("\\\"")
            '\\' -> append("\\\\")
            '%' -> append("\\u0025")
            '\n' -> append("\\n")
            '\t' -> append("\\t")
            '\r' -> Unit
            else -> append(c)
        }
    }
    // A leading @ or ? would be read as a resource reference.
    if (startsWith("@") || startsWith("?")) insert(0, '\\')
}

private fun xmlComment(text: String): String = text.replace("--", "- -")

/** A Kotlin source being written: its imports and body. */
internal class KtFile(private val pkg: String) {
    val w = Writer()
    private val imports = HashSet<String>()
    val res: String = "$pkg.generated.resources"

    fun import(vararg names: String) {
        imports += names
    }

    /** `stringResource(Res.string.key)`, importing what it needs. */
    fun str(key: String): String {
        import("$res.Res", "$res.$key", "org.jetbrains.compose.resources.stringResource")
        return "stringResource(Res.string.$key)"
    }

    /** `COUIIcons.Name`, importing it. */
    fun icon(name: String): String {
        import("io.github.suqi8.coui.kmp.icon.COUIIcons", "io.github.suqi8.coui.kmp.icon.extended.$name")
        return "COUIIcons.$name"
    }

    fun render(header: String): String = buildString {
        append(header)
        append("package ").append(pkg).append("\n\n")
        val tail = listOf("java.", "javax.", "kotlin.")
        val sorted = imports.filter { it.substringBeforeLast('.') != pkg }.sortedWith(compareBy({ i -> tail.any { i.startsWith(it) } }, { it }))
        sorted.forEach { append("import ").append(it).append('\n') }
        if (sorted.isNotEmpty()) append('\n')
        append(w.text())
    }
}

/** A call argument: a plain `name = expr` ([V]) or a lambda written over several lines ([L]). */
internal sealed interface Arg {
    data class V(val name: String, val expr: String) : Arg

    data class L(val name: String, val head: String = "{", val body: Writer.() -> Unit) : Arg
}

/** Writes indented Kotlin. */
internal class Writer {
    private val sb = StringBuilder()
    var indent = 0

    fun text(): String = sb.toString()

    fun line(s: String = "") {
        if (s.isNotEmpty()) sb.append("    ".repeat(indent)).append(s)
        sb.append('\n')
    }

    fun indented(body: Writer.() -> Unit) {
        indent++
        body()
        indent--
    }

    /** `open` … `close` with the body indented one level. */
    fun block(open: String, close: String = "}", body: Writer.() -> Unit) {
        if (open.isNotEmpty()) line(open)
        indented(body)
        if (close.isNotEmpty()) line(close)
    }

    /**
     * `fn(args)` with an optional trailing lambda. Short calls of plain arguments stay on one line;
     * others put each argument on its own line with a trailing comma.
     */
    fun call(fn: String, args: List<Arg>, prefix: String = "", lambdaParams: String = "", trailing: (Writer.() -> Unit)? = null) {
        val simple = args.all { it is Arg.V && !it.expr.contains('\n') }
        val one = args.joinToString(", ") { a -> (a as? Arg.V)?.let { if (it.name.isEmpty()) it.expr else "${it.name} = ${it.expr}" }.orEmpty() }
        val open = if (trailing != null) (if (lambdaParams.isEmpty()) " {" else " { $lambdaParams") else ""
        val head = if (args.isEmpty() && trailing != null) "$prefix$fn" else "$prefix$fn($one)"
        if (simple && indent * 4 + head.length + open.length <= MAX_LINE) {
            if (trailing != null) block(head + open, "}", trailing) else line(head)
            return
        }
        line("$prefix$fn(")
        indented {
            args.forEach { a ->
                when (a) {
                    is Arg.V -> line((if (a.name.isEmpty()) a.expr else "${a.name} = ${a.expr}") + ",")
                    is Arg.L -> block("${a.name} = ${a.head}", "},", a.body)
                }
            }
        }
        if (trailing != null) block(")$open", "}", trailing) else line(")")
    }

    companion object {
        const val MAX_LINE = 120
    }
}

/** A piece of state a page keeps. */
private data class State(val name: String, val decl: String)

/** Writes one `<Ident>Page.kt`. */
private class PageWriter(
    val doc: CanvasDoc,
    val plan: AppPlan,
    val s: ScreenPlan,
    pkg: String,
    val strings: StringTable,
) {
    val f = KtFile(pkg)
    val w = f.w
    private val callbacks = pageCallbacks(plan, s)
    private val names = HashSet<String>()
    private val states = mutableListOf<State>()

    /** State per item id (or per group id for single-choice row runs). */
    private val stateOf = HashMap<String, String>()

    /** The `show` flag per overlay group id. */
    private val showOf = HashMap<String, String>()

    /** Overlay group id per item that opens it. */
    private val opens = HashMap<String, String>()
    private val contentWidth = contentWidth(s.frame)
    private var searchQuery: String? = null

    private fun str(text: String, hint: String): String = f.str(strings.key(s.snake, text, hint))

    private fun icon(name: String): String = f.icon(if (name in canvas.model.IconNames) name else FALLBACK_ICON)

    private fun unique(base: String): String {
        var n = base
        var i = 2
        while (n in names || n in RESERVED) n = "$base${i++}"
        names += n
        return n
    }

    private fun base(text: String, fallback: String): String = Names.camel(text).ifEmpty { fallback }

    private fun state(key: String, name: String, type: String, init: String): String {
        val n = unique(name)
        f.import("androidx.compose.runtime.getValue", "androidx.compose.runtime.setValue", "androidx.compose.runtime.saveable.rememberSaveable")
        val factory = when (type) {
            "Int" -> "mutableIntStateOf".also { f.import("androidx.compose.runtime.mutableIntStateOf") }
            "Float" -> "mutableFloatStateOf".also { f.import("androidx.compose.runtime.mutableFloatStateOf") }
            else -> "mutableStateOf".also { f.import("androidx.compose.runtime.mutableStateOf") }
        }
        states += State(n, "var $n by rememberSaveable { $factory($init) }")
        stateOf[key] = n
        return n
    }

    /** Allocates the page state before writing, so declarations come first. */
    private fun allocate() {
        callbacks.forEach { names += it.name }
        names += "modifier"
        s.topBar?.item?.takeIf { it.variant == "home" }?.let { searchQuery = state(it.id, "searchQuery", "String", "\"\"") }
        s.overlays.forEach { o ->
            val kindName = if (o.part.kind == Kind.Dialog) "Dialog" else "Sheet"
            val b = Names.pascal(Names.words(o.part.item.label).take(3).joinToString(" "))
            val n = state(o.part.group.id, "show$b$kindName", "Boolean", "false")
            showOf[o.part.group.id] = n
            o.opener?.let { opens[it.id] = o.part.group.id }
        }
        val all = s.body.flatMap { it.parts } + s.overlays.flatMap { o -> o.content.flatMap { it.parts } } + listOfNotNull(s.bottomNav)
        all.forEach { p -> allocatePart(p) }
    }

    private fun allocatePart(p: Part) {
        if (p.isRowRun) {
            val radios = p.items.filter { Kind.of(it.kind) == Kind.RadioRow }
            if (radios.isNotEmpty()) {
                val init = radios.indexOfFirst { it.checked == true }.coerceAtLeast(0)
                val n = state(p.group.id + ":radio", base(radios.first().label, "option") + "Choice", "Int", "$init")
                radios.forEach { stateOf[it.id] = n }
            }
            val marks = p.items.filter { Kind.of(it.kind) == Kind.MarkRow }
            if (marks.size > 1 && marks.count { it.checked == true } <= 1) {
                val init = marks.indexOfFirst { it.checked == true }.coerceAtLeast(0)
                val n = state(p.group.id + ":mark", base(marks.first().label, "mark") + "Choice", "Int", "$init")
                marks.forEach { stateOf[it.id] = n }
            }
        }
        p.items.forEach { item ->
            if (item.id in stateOf) return@forEach
            when (Kind.of(item.kind)) {
                Kind.SwitchRow, Kind.CheckboxRow -> state(item.id, base(item.label, "option") + "Checked", "Boolean", "${item.checked == true}")

                Kind.MarkRow -> state(item.id, base(item.label, "mark") + "Checked", "Boolean", "${item.checked == true}")

                Kind.Chip -> if (item.action == null) state(item.id, base(item.label, "chip") + "Selected", "Boolean", "${item.checked == true}")

                Kind.DropdownRow -> state(item.id, base(item.label, "option") + "Index", "Int", "${item.selected ?: 0}")

                Kind.SliderRow, Kind.Slider -> state(item.id, base(item.label, "slider") + "Value", "Float", "${(item.value ?: 0f).roundToInt()}f")

                Kind.InputRow, Kind.TextField -> state(item.id, base(item.label, "input") + "Text", "String", "\"\"")

                Kind.Tabs -> state(item.id, "selectedTab", "Int", "${item.selected ?: 0}")

                Kind.SearchBar -> {
                    state(item.id, "searchQuery", "String", "\"\"")
                    state(item.id + ":expanded", "searchExpanded", "Boolean", "false")
                }

                Kind.BottomNav -> {
                    val tabs = item.tabs.orEmpty()
                    val sel = item.selected ?: 0
                    if (tabs.indices.any { it != sel && edge(item, NavEdge.TAB + it) == null }) state(item.id, "selectedNavItem", "Int", "$sel")
                }

                else -> Unit
            }
        }
    }

    private fun edge(item: Item, trigger: String = NavEdge.TAP): NavEdge? = plan.edgesFrom(s.frame.id).firstOrNull { it.item?.id == item.id && it.trigger == trigger }

    /** The callback a navigation edge calls, or null when it goes nowhere useful. */
    private fun callbackOf(e: NavEdge?): String? {
        e ?: return null
        if (e.isBack) return "onBack"
        if (e.to == s.frame.id) return null
        return plan.screen(e.to)?.let { "onOpen${it.ident}" }
    }

    /** The statements a tap on [item] (with [trigger]) runs. */
    private fun tap(item: Item, trigger: String = NavEdge.TAP, before: List<String> = emptyList()): List<String> {
        val nav = callbackOf(edge(item, trigger))?.let { "$it()" }
        val show = if (trigger == NavEdge.TAP) opens[item.id]?.let { showOf[it] }?.let { "$it = true" } else null
        return before + listOfNotNull(show, nav)
    }

    /** A lambda expression for [stmts]: a callback passed as is, `{ a }`, or null when there is nothing to do. */
    private fun lambda(stmts: List<String>): String? = when {
        stmts.isEmpty() -> null
        stmts.size == 1 && stmts[0].endsWith("()") && stmts[0].dropLast(2).all { it.isLetterOrDigit() } -> stmts[0].dropLast(2)
        stmts.size == 1 -> "{ ${stmts[0]} }"
        else -> null
    }

    /** An argument running [stmts] on tap; [required] arguments get `{}` when there is nothing to do. */
    private fun clickArg(name: String, stmts: List<String>, required: Boolean): Arg? {
        lambda(stmts)?.let { return Arg.V(name, it) }
        if (stmts.isEmpty()) return if (required) Arg.V(name, "{}") else null
        return Arg.L(name) { stmts.forEach { line(it) } }
    }

    private fun notes(item: Item) {
        item.note?.takeIf { it.isNotBlank() }?.lines()?.filter { it.isNotBlank() }?.forEachIndexed { i, l ->
            w.line((if (i == 0) "// TODO: " else "//  ") + l.trim())
        }
    }

    private fun mod(chain: String): String {
        f.import("androidx.compose.ui.Modifier")
        return "Modifier$chain"
    }

    private fun dp(v: Float): String {
        f.import("androidx.compose.ui.unit.dp")
        return "${v.roundToInt()}.dp"
    }

    private fun padding(): String {
        f.import("androidx.compose.foundation.layout.padding")
        return ".padding(horizontal = ${dp(16f)}).padding(bottom = ${dp(16f)})"
    }

    fun write(): String {
        allocate()
        f.import("androidx.compose.runtime.Composable", "androidx.compose.ui.Modifier")
        val frame = s.frame
        val doc = oneLine(frame.note.orEmpty()).replace("*/", "* /").ifEmpty { "The ${oneLine(frame.name).ifEmpty { s.ident }.replace("*/", "* /")} screen." }
        w.line("/** $doc */")
        w.line("@Composable")
        w.line("fun ${s.ident}Page(")
        w.indented {
            callbacks.forEach { line("${it.name}: () -> Unit,") }
            line("modifier: Modifier = Modifier,")
        }
        w.block(") {") {
            states.forEach { line(it.decl) }
            if (s.snackbar != null) {
                f.import("androidx.compose.runtime.remember", "io.github.suqi8.coui.kmp.basic.SnackbarHostState")
                line("val snackbarHostState = remember { SnackbarHostState() }")
            }
            page()
        }
        return f.render("// Generated by COUI Canvas.\n")
    }

    private fun page() {
        val bar = s.topBar?.item
        val scaffold = s.bottomNav != null || s.fab != null || bar == null
        val args = mutableListOf<Arg>()
        args += Arg.V("title", bar?.label?.takeIf { it.isNotBlank() }?.let { str(it, "title") } ?: "\"\"")
        args += Arg.V("modifier", "modifier")
        bar?.supporting?.takeIf { it.isNotBlank() && bar.variant != "home" }?.let { args += Arg.V("subtitle", str(it, "subtitle")) }
        if (bar != null) callbackOf(edge(bar, NavEdge.ICON))?.let { args += Arg.V("onBack", it) }
        when (bar?.variant) {
            "home" -> args += Arg.V("topBarStyle", "CouiTopBarStyle.SettingsHome")
            "small" -> args += Arg.V("topBarStyle", "CouiTopBarStyle.Small")
            else -> if (bar != null) args += Arg.V("wide", "isWideWindow()")
        }
        bar?.icon2?.let { name ->
