    private fun summary(item: Item): Arg? = item.supporting?.takeIf { it.isNotBlank() }?.let { Arg.V("summary", str(it, "summary")) }

    private fun title(item: Item, hint: String = "title"): String = if (item.label.isBlank()) "\"\"" else str(item.label, hint)

    /** One preference row inside a `CardListGroup` item. */
    private fun row(p: Part, item: Item) {
        notes(item)
        val v = stateOf[item.id]
        val pref = "io.github.suqi8.coui.kmp.preference"
        when (Kind.of(item.kind)) {
            Kind.SwitchRow -> {
                f.import("$pref.SwitchPreference")
                w.call(
                    "SwitchPreference",
                    listOfNotNull(Arg.V("checked", v!!), Arg.V("onCheckedChange", "{ $v = it }"), Arg.V("title", title(item, "switch")), summary(item), startIcon(item)),
                )
            }

            Kind.ArrowRow -> {
                f.import("$pref.ArrowPreference")
                w.call("ArrowPreference", listOfNotNull(Arg.V("title", title(item, "entry")), summary(item), startIcon(item), endValue(item), clickArg("onClick", tap(item), required = false)))
            }

            Kind.BasicRow -> {
                f.import("io.github.suqi8.coui.kmp.basic.BasicComponent")
                w.call("BasicComponent", listOfNotNull(Arg.V("title", title(item, "action")), summary(item), startIcon(item), endValue(item), clickArg("onClick", tap(item), required = false)))
            }

            Kind.DropdownRow -> {
                f.import("$pref.OverlayDropdownPreference")
                val options = item.tabs.orEmpty().mapIndexed { i, t -> str(t.label, "option${i + 1}") }
                val items = if (options.isEmpty()) "emptyList()" else "listOf(${options.joinToString(", ")})"
                w.call(
                    "OverlayDropdownPreference",
                    listOfNotNull(
                        Arg.V("items", items),
                        Arg.V("selectedIndex", v!!),
                        Arg.V("title", title(item, "dropdown")),
                        summary(item),
                        startIcon(item),
                        Arg.V("onSelectedIndexChange", "{ $v = it }"),
                    ),
                )
            }

            Kind.CheckboxRow -> {
                f.import("$pref.CheckboxPreference")
                w.call("CheckboxPreference", listOfNotNull(Arg.V("title", title(item, "checkbox")), Arg.V("checked", v!!), Arg.V("onCheckedChange", "{ $v = it }"), summary(item)))
            }

            Kind.RadioRow -> {
                f.import("$pref.RadioButtonPreference")
                val index = p.items.filter { Kind.of(it.kind) == Kind.RadioRow }.indexOf(item)
                w.call("RadioButtonPreference", listOfNotNull(Arg.V("title", title(item, "radio")), Arg.V("selected", "$v == $index"), Arg.V("onClick", "{ $v = $index }"), summary(item)))
            }

            Kind.MarkRow -> {
                f.import("$pref.MarkPreference")
                val marks = p.items.filter { Kind.of(it.kind) == Kind.MarkRow }
                val grouped = stateOf[p.group.id + ":mark"] != null
                val index = marks.indexOf(item)
                val checked = if (grouped) "$v == $index" else v!!
                val click = if (grouped) "{ $v = $index }" else "{ $v = !$v }"
                w.call("MarkPreference", listOfNotNull(Arg.V("title", title(item, "mark")), Arg.V("checked", checked), Arg.V("onClick", click), summary(item)))
            }

            Kind.SliderRow -> {
                f.import("$pref.SliderPreference")
                w.call(
                    "SliderPreference",
                    listOfNotNull(
                        Arg.V("value", v!!),
                        Arg.V("onValueChange", "{ $v = it }"),
                        item.label.takeIf { it.isNotBlank() }?.let { Arg.V("title", str(it, "slider")) },
                        summary(item),
                        item.end?.takeIf { it.isNotBlank() }?.let { Arg.V("valueText", str(it, "value")) },
                        Arg.V("valueRange", "0f..100f"),
                    ),
                )
            }

            Kind.InputRow -> {
                f.import("$pref.InputPreference")
                w.call(
                    "InputPreference",
                    listOfNotNull(
                        Arg.V("value", v!!),
                        Arg.V("onValueChange", "{ $v = it }"),
                        item.label.takeIf { it.isNotBlank() }?.let { Arg.V("title", str(it, "input")) },
                        item.supporting?.takeIf { it.isNotBlank() }?.let { Arg.V("hint", str(it, "hint")) },
                    ),
                )
            }

            else -> item(p, item, null)
        }
    }

    /** One non-row item. */
    private fun item(p: Part, item: Item, modifier: String?) {
        val kind = Kind.of(item.kind) ?: return
        if (kind.family == Family.Row) {
            // A lone row outside a run still belongs in a card.
            cardRun(p, modifier ?: mod(padding()))
            return
        }
        notes(item)
        val m = modifier?.let { Arg.V("modifier", it) }
        val basic = "io.github.suqi8.coui.kmp.basic"
        when (kind) {
            Kind.Category -> {
                f.import("io.github.suqi8.coui.kmp.preference.PreferenceCategory")
                w.call("PreferenceCategory", listOfNotNull(Arg.V("title", title(item, "category")), m))
            }

            Kind.Button -> {
                f.import("$basic.TextButton")
                val colors = if (item.variant != "secondary") {
                    f.import("$basic.ButtonDefaults")
                    Arg.V("colors", "ButtonDefaults.textButtonColorsPrimary()")
                } else {
                    null
                }
                w.call("TextButton", listOfNotNull(Arg.V("text", title(item, "button")), clickArg("onClick", tap(item), required = true), m, colors))
            }

            Kind.IconButton -> {
                f.import("$basic.IconButton", "$basic.Icon", "io.github.suqi8.coui.kmp.theme.COUITheme")
                w.call("IconButton", listOfNotNull(clickArg("onClick", tap(item), required = true), m)) {
                    line("Icon(imageVector = ${icon(item.icon ?: FALLBACK_ICON)}, contentDescription = null, tint = COUITheme.colorScheme.labelPrimary)")
                }
            }

            Kind.Chip -> {
                f.import("$basic.Chip")
                val v = stateOf[item.id]
                val selected = v ?: "${item.checked == true}"
                val click = if (v != null) clickArg("onClick", tap(item, before = listOf("$v = !$v")), required = true) else clickArg("onClick", tap(item), required = true)
                val iconArg = item.icon?.let { name ->
                    f.import("$basic.Icon")
                    Arg.L("icon") { line("Icon(imageVector = ${icon(name)}, contentDescription = null)") }
                }
                w.call("Chip", listOfNotNull(Arg.V("selected", selected), click, Arg.V("label", title(item, "chip")), m, iconArg))
            }

            Kind.Card -> {
                f.import("$basic.Card", "$basic.Text", "io.github.suqi8.coui.kmp.theme.COUITheme", "androidx.compose.foundation.layout.PaddingValues")
                val cm = item.size2?.let {
                    f.import("androidx.compose.foundation.layout.height")
                    (modifier ?: mod("")) + ".height(${dp(it)})"
                } ?: modifier
                val click = clickArg("onClick", tap(item), required = false)
                w.call("Card", listOfNotNull(cm?.let { Arg.V("modifier", it) }, Arg.V("insideMargin", "PaddingValues(${dp(16f)})"), click)) {
                    item.icon?.let { name ->
                        f.import("$basic.Icon", "androidx.compose.foundation.layout.size")
                        call(
                            "Icon",
                            listOf(
                                Arg.V("imageVector", icon(name)),
                                Arg.V("contentDescription", "null"),
                                Arg.V("modifier", mod(".size(${dp(24f)})")),
                                Arg.V("tint", "COUITheme.colorScheme.primary"),
                            ),
                        )
                    }
                    if (item.label.isNotBlank()) line("Text(text = ${str(item.label, "card_title")}, style = COUITheme.textStyles.headlineXS)")
                    item.supporting?.takeIf { it.isNotBlank() }?.let {
                        call("Text", listOf(Arg.V("text", str(it, "card_text")), Arg.V("style", "COUITheme.textStyles.bodyS"), Arg.V("color", "COUITheme.colorScheme.labelSecondary")))
                    }
                }
            }

            Kind.Text -> {
                f.import("$basic.Text", "io.github.suqi8.coui.kmp.theme.COUITheme")
                val (style, color) = when (item.variant) {
                    "title" -> "headlineXS" to null
                    "caption" -> "bodyS" to "labelSecondary"
                    else -> "bodyL" to null
                }
                w.call("Text", listOfNotNull(Arg.V("text", title(item, "text")), m, color?.let { Arg.V("color", "COUITheme.colorScheme.$it") }, Arg.V("style", "COUITheme.textStyles.$style")))
            }

            Kind.Image -> {
                f.import(
                    "androidx.compose.foundation.background",
                    "androidx.compose.foundation.layout.Box",
                    "androidx.compose.foundation.layout.height",
                    "androidx.compose.foundation.shape.RoundedCornerShape",
                    "androidx.compose.ui.draw.clip",
                    "io.github.suqi8.coui.kmp.theme.COUITheme",
                )
                val h = item.size2 ?: p.box.h
                w.line("// TODO: the image" + (item.label.takeIf { it.isNotBlank() }?.let { " \"${oneLine(it)}\"" } ?: "") + ": replace this placeholder with Image(painterResource(…)).")
                val box = (modifier ?: mod("")) + ".height(${dp(h)}).clip(RoundedCornerShape(${dp(16f)})).background(COUITheme.colorScheme.container8)"
                w.call("Box", listOf(Arg.V("modifier", box)))
            }

            Kind.TopTips -> {
                f.import("$basic.TopTips")
                val action = item.supporting?.takeIf { it.isNotBlank() }
                w.call(
                    "TopTips",
                    listOfNotNull(
                        Arg.V("text", title(item, "tips")),
                        m,
                        action?.let { Arg.V("actionText", str(it, "tips_action")) },
                        clickArg("onAction", tap(item), required = false),
                    ),
                )
            }

            Kind.EmptyState -> {
                f.import("$basic.EmptyState")
                val action = item.end?.takeIf { it.isNotBlank() }
                w.call(
                    "EmptyState",
                    listOfNotNull(
                        Arg.V("title", title(item, "empty_title")),
                        m,
                        item.supporting?.takeIf { it.isNotBlank() }?.let { Arg.V("subtitle", str(it, "empty_subtitle")) },
                        action?.let { Arg.V("actionText", str(it, "empty_action")) },
                        clickArg("onActionClick", tap(item), required = false),
                    ),
                )
            }

            Kind.TextField -> {
                f.import("$basic.TextField", "$basic.TextFieldMode")
                val v = stateOf[item.id]!!
                w.call(
                    "TextField",
                    listOfNotNull(
                        Arg.V("value", v),
                        Arg.V("onValueChange", "{ $v = it }"),
                        m,
                        Arg.V("backgroundMode", if (item.variant == "filled") "TextFieldMode.Rectangle" else "TextFieldMode.Line"),
                        (item.label.takeIf { it.isNotBlank() } ?: item.supporting?.takeIf { it.isNotBlank() })?.let { Arg.V("label", str(it, "field")) },
                        Arg.V("singleLine", "true"),
                    ),
                )
            }

            Kind.Slider -> {
                f.import("$basic.Slider")
                val v = stateOf[item.id]!!
                w.call("Slider", listOfNotNull(Arg.V("value", v), Arg.V("onValueChange", "{ $v = it }"), m, Arg.V("valueRange", "0f..100f")))
            }

            Kind.Progress -> {
                val progress = "${((item.value ?: 0f) / 100f).toString().take(5)}f"
                when (item.variant) {
                    "circular" -> {
                        f.import("$basic.CircularProgressIndicator")
                        w.call("CircularProgressIndicator", listOfNotNull(m, Arg.V("progress", progress)))
                    }

                    "loading" -> {
                        f.import("$basic.InfiniteProgressIndicator")
                        w.call("InfiniteProgressIndicator", listOfNotNull(m))
                    }

                    else -> {
                        f.import("$basic.LinearProgressIndicator")
                        w.call("LinearProgressIndicator", listOfNotNull(m, Arg.V("progress", progress)))
                    }
                }
            }

            Kind.Divider -> {
                f.import("$basic.HorizontalDivider")
                w.call("HorizontalDivider", listOfNotNull(m))
            }

            Kind.SearchBar -> {
                f.import("$basic.SearchBar", "$basic.InputField")
                val q = stateOf[item.id]!!
                val ex = stateOf[item.id + ":expanded"]!!
                val opensPage = callbackOf(edge(item))
                val expand = if (opensPage != null) "{ if (it) $opensPage() }" else "{ $ex = it }"
                w.call(
                    "SearchBar",
                    listOfNotNull(
                        Arg.L("inputField") {
                            call(
                                "InputField",
                                listOfNotNull(
                                    Arg.V("query", q),
                                    Arg.V("onQueryChange", "{ $q = it }"),
                                    Arg.V("onSearch", "{}"),
                                    Arg.V("expanded", ex),
                                    Arg.V("onExpandedChange", expand),
                                    item.label.takeIf { it.isNotBlank() }?.let { Arg.V("label", str(it, "search_hint")) },
                                ),
                            )
                        },
                        Arg.V("onExpandedChange", expand),
                        m,
                        Arg.V("expanded", ex),
                    ),
                ) {
                    line("// TODO: search results")
                }
            }

            Kind.Tabs -> {
                val v = stateOf[item.id]!!
                val tabs = item.tabs.orEmpty().mapIndexed { i, t -> str(t.label, "tab${i + 1}") }
                val comp = if (item.variant == "contour") "TabRowWithContour" else "TabRow"
                f.import("$basic.$comp")
                val navs = item.tabs.orEmpty().indices.mapNotNull { i -> callbackOf(edge(item, NavEdge.TAB + i))?.let { i to it } }
                val select: Arg = if (navs.isEmpty()) {
                    Arg.V("onTabSelected", "{ $v = it }")
                } else {
                    Arg.L("onTabSelected", "{ index ->") {
                        line("$v = index")
                        navs.forEach { (i, cb) -> line("if (index == $i) $cb()") }
                    }
                }
                w.call(comp, listOfNotNull(Arg.V("tabs", if (tabs.isEmpty()) "emptyList()" else "listOf(${tabs.joinToString(", ")})"), Arg.V("selectedTabIndex", v), select, m))
            }

            else -> {
                w.line("// ${kind.component} \"${oneLine(item.label)}\" is drawn twice on this screen; only the first one is used.")
            }
        }
    }

    private fun bottomNav(item: Item) {
        f.import("io.github.suqi8.coui.kmp.basic.FloatingNavigationBar", "io.github.suqi8.coui.kmp.basic.FloatingNavigationBarItem")
        notes(item)
        val v = stateOf[item.id]
        val sel = item.selected ?: 0
        w.block("FloatingNavigationBar {") {
            item.tabs.orEmpty().forEachIndexed { i, tab ->
                val nav = callbackOf(edge(item, NavEdge.TAB + i))
                val click = when {
                    nav != null -> Arg.V("onClick", nav)
                    v != null -> Arg.V("onClick", "{ $v = $i }")
                    else -> Arg.V("onClick", "{}")
                }
                call(
                    "FloatingNavigationBarItem",
                    listOf(
                        Arg.V("selected", if (v != null) "$v == $i" else "${i == sel}"),
                        click,
                        Arg.V("icon", icon(tab.icon ?: FALLBACK_ICON)),
                        Arg.V("label", if (tab.label.isBlank()) "\"\"" else str(tab.label, "nav${i + 1}")),
                    ),
                )
            }
        }
    }

    private fun fab(item: Item) {
        f.import("io.github.suqi8.coui.kmp.basic.FloatingActionButton", "io.github.suqi8.coui.kmp.basic.Icon", "io.github.suqi8.coui.kmp.theme.COUITheme")
        notes(item)
        w.call("FloatingActionButton", listOfNotNull(clickArg("onClick", tap(item), required = true))) {
            line("Icon(imageVector = ${icon(item.icon ?: "Add")}, contentDescription = null, tint = COUITheme.colorScheme.onPrimary)")
        }
    }

    private fun overlays() {
        val dialogs = s.overlays.any { it.part.kind == Kind.Dialog }
        val sheets = s.overlays.any { it.part.kind == Kind.BottomSheet }
        if (dialogs || sheets) f.import("io.github.suqi8.coui.kmp.blur.MaterialBlurDefaults")
        if (dialogs) w.line("val dialogBlur = panelBlur(MaterialBlurDefaults::dialog)")
        if (sheets) w.line("val sheetBlur = panelBlur(MaterialBlurDefaults::bottomSheet)")
        s.overlays.forEach { o ->
            val show = showOf.getValue(o.part.group.id)
            val item = o.part.item
            notes(item)
            if (o.opener == null) w.line("// TODO: set $show = true from the tap that opens this; the design draws it open.")
            if (o.part.kind == Kind.Dialog) dialog(o, item, show) else sheet(o, item, show)
        }
    }

    private fun dialog(o: Overlay, item: Item, show: String) {
        f.import("io.github.suqi8.coui.kmp.overlay.OverlayDialog", "io.github.suqi8.coui.kmp.layout.DialogDefaults")
        val args = listOfNotNull(
            Arg.V("show", show),
            item.label.takeIf { it.isNotBlank() }?.let { Arg.V("title", str(it, "dialog_title")) },
            item.supporting?.takeIf { it.isNotBlank() }?.let { Arg.V("summary", str(it, "dialog_message")) },
            Arg.V("backgroundModifier", "dialogBlur?.backgroundModifier ?: Modifier"),
            Arg.V("backgroundColor", "dialogBlur?.backgroundColor ?: DialogDefaults.backgroundColor()"),
            Arg.V("materialStroke", "dialogBlur != null"),
            Arg.V("onDismissRequest", "{ $show = false }"),
        )
        w.call("OverlayDialog", args) {
            overlayContent(o)
            val labels = item.tabs.orEmpty().map { it.label }.ifEmpty { listOfNotNull(item.end?.takeIf { it.isNotBlank() }) }
            if (labels.isNotEmpty()) {
                f.import("io.github.suqi8.coui.kmp.layout.DialogButtonBar", "io.github.suqi8.coui.kmp.layout.DialogButtonBarAction")
                val slots = dialogSlots(labels.size)
                val byslot = labels.indices.filter { slots[it] != "extra" }.associateBy { slots[it] }
                fun action(i: Int): Arg.L {
                    val trigger = if (item.tabs.isNullOrEmpty()) NavEdge.TAP else NavEdge.TAB + i
                    val stmts = listOf("$show = false") + listOfNotNull(callbackOf(edge(item, trigger))?.let { "$it()" })
                    val recommended = slots[i] == "positive" && labels.size > 1
                    return Arg.L(slots[i], "DialogButtonBarAction(") {
                        line("text = ${str(labels[i], "button${i + 1}")},")
                        if (recommended) line("recommended = true,")
                        if (stmts.size == 1) {
                            line("onClick = { ${stmts[0]} },")
                        } else {
                            block("onClick = {", "},") { stmts.forEach { line(it) } }
                        }
                    }
                }
                val args2 = listOf("negative", "positive", "neutral").map { slot ->
                    byslot[slot]?.let { action(it) } ?: Arg.V(slot, "null")
                }.filterNot { it is Arg.V && it.name == "neutral" }
                // DialogButtonBarAction(…) closes with `)`, so write the bar by hand.
                block("DialogButtonBar(", ")") {
                    args2.forEach { a ->
                        when (a) {
                            is Arg.V -> line("${a.name} = ${a.expr},")
                            is Arg.L -> block("${a.name} = ${a.head}", "),", a.body)
                        }
                    }
                }
            }
        }
    }

    private fun sheet(o: Overlay, item: Item, show: String) {
        f.import("io.github.suqi8.coui.kmp.overlay.OverlayBottomSheet", "io.github.suqi8.coui.kmp.layout.BottomSheetDefaults")
        val args = listOfNotNull(
            Arg.V("show", show),
            item.label.takeIf { it.isNotBlank() }?.let { Arg.V("title", str(it, "sheet_title")) },
            Arg.V("backgroundModifier", "sheetBlur?.backgroundModifier ?: Modifier"),
            Arg.V("backgroundColor", "sheetBlur?.backgroundColor ?: BottomSheetDefaults.backgroundColor()"),
            Arg.V("materialStroke", "sheetBlur != null"),
            Arg.V("onDismissRequest", "{ $show = false }"),
        )
        w.call("OverlayBottomSheet", args) {
            if (o.content.isEmpty()) line("// TODO: the sheet's content") else overlayContent(o)
        }
    }

    private fun overlayContent(o: Overlay) {
        if (o.content.isEmpty()) return
        f.import("androidx.compose.foundation.layout.Column")
        w.block("Column {") { o.content.forEach { writeBlock(it, inset = false) } }
    }

